namespace ArchiveFixer.Models
{
    /// <summary>
    /// 源包处理档（决策 D-9，2026-09-22 用户拍板）。
    ///
    /// <para>
    /// ⚠ <b>两条路径都照这一档走</b>（用户 2026-09-22 的版本二指示，**推翻**了早先"地基路径永远不动源包"的说法）：
    /// 「一键处理」与手动「只解压」都在"成功 + 输出校验通过 + 未取消 + 属于本任务分卷组"之后
    /// 按本档处理源包（见 AGENTS.md §0 / §6 第 1 条的例外、`docs/输出与整理模型.md` §3.4）。
    /// <see cref="SourceHandlingMode.KeepInPlace"/> 才是"一个字节都不搬"的出口。
    /// </para>
    /// </summary>
    public enum SourceHandlingMode
    {
        /// <summary>源包留在原地，一个字节都不动（**默认档**）。</summary>
        KeepInPlace = 0,

        /// <summary>
        /// 成功（定稿 + 输出校验通过 + 未取消 + 可证完整 + 属于本任务分卷组）之后**就地彻底删除**源包
        /// （分卷组 = 整组一起删）。
        ///
        /// <para>⛔ **不搬进「其余物」**（用户 2026-10-14 下午订正，逐字：「原包一直在原来的位置，
        /// 选『彻底删除』也是就地删、⛔ 不搬进其余物」）；⛔ 失败 / 部分完成 / 取消 ⇒ 一个字节都不动
        /// （不变量 1，任何设置都不改变这一条）。</para>
        ///
        /// <para>⚠ 2026-10-15：原来的 <c>MoveToRest</c>（把整组源包移入其余物）**整条删除** ——
        /// 用户口径是「源包操作……就两个选项，**留下和彻底删除（默认留下）**」。</para>
        /// </summary>
        DeleteInPlace = 1
    }
}
